#!/usr/bin/env python3
"""
Generate comparison tables for Phase 05 (Baseline vs Extra/Ensemble)
- Reads JSON metrics from results/05_modeling and results/05_modeling/extra
- Writes seminar-paper/tables/phase05_modeling_comparison.tex

Columns: Horizon | Baseline Best (AUC) | Extra/Ensemble Best (AUC) | Overall Best (AUC)
"""

import json
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
MOD_RESULTS = ROOT / "results" / "05_modeling"
EXTRA_RESULTS = MOD_RESULTS / "extra"
TABLES_DIR = ROOT / "seminar-paper" / "tables"
TABLES_DIR.mkdir(parents=True, exist_ok=True)


def _read_dir(dirpath: Path) -> dict:
    by_h: dict = {}
    for p in sorted(dirpath.glob("H*_metrics.json")):
        try:
            blob = json.loads(p.read_text())
        except Exception:
            continue
        h_raw = blob.get("horizon")
        if h_raw is None:
            continue
        h = f"H{int(h_raw)}"
        metrics = blob.get("metrics", {}) or {}
        by_h.setdefault(h, {})
        for name, vals in metrics.items():
            auc = vals.get("roc_auc_mean")
            if auc is not None:
                by_h[h][str(name)] = float(auc)
    return by_h


def build_dataframe() -> pd.DataFrame:
    base = _read_dir(MOD_RESULTS)
    extra = _read_dir(EXTRA_RESULTS) if EXTRA_RESULTS.exists() else {}

    horizons = sorted(set(base.keys()) | set(extra.keys()))
    rows = []
    for h in horizons:
        base_map = base.get(h, {})
        extra_map = extra.get(h, {})

        base_best_name, base_best_auc = ("--", float("nan"))
        if base_map:
            base_best_name, base_best_auc = max(base_map.items(), key=lambda kv: kv[1])

        extra_best_name, extra_best_auc = ("--", float("nan"))
        if extra_map:
            extra_best_name, extra_best_auc = max(extra_map.items(), key=lambda kv: kv[1])

        all_map = {}
        all_map.update(base_map)
        all_map.update(extra_map)
        overall_name, overall_auc = ("--", float("nan"))
        if all_map:
            overall_name, overall_auc = max(all_map.items(), key=lambda kv: kv[1])

        rows.append(
            {
                "Horizon": h,
                "Baseline_Best": base_best_name,
                "Baseline_AUC": base_best_auc,
                "ExtraEnsemble_Best": extra_best_name,
                "ExtraEnsemble_AUC": extra_best_auc,
                "Overall_Best": overall_name,
                "Overall_AUC": overall_auc,
            }
        )
    return pd.DataFrame(rows)


def _esc(text: str) -> str:
    s = str(text) if text is not None else ""
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    for k, v in replacements.items():
        s = s.replace(k, v)
    return s


def write_tex(df: pd.DataFrame, out_path: Path) -> None:
    lines = []
    nl = "\\\\"
    lines.append("% Auto-generated by generate_phase05_comparison_tables.py")
    lines.append("\\begin{table}[H]")
    lines.append("  \\centering")
    lines.append("  \\caption{Baseline vs. Extra/Ensemble je Horizont (ROC-AUC)}")
    lines.append("  \\label{tab:phase05_modeling_comparison}")
    lines.append("  \\begin{tabular}{l l r l r l r}")
    lines.append("    \\toprule")
    lines.append("    Horizont & Baseline (Best) & ROC-AUC & Extra/Ensemble (Best) & ROC-AUC & Overall (Best) & ROC-AUC " + nl)
    lines.append("    \\midrule")
    for _, r in df.sort_values("Horizon").iterrows():
        h = r["Horizon"]
        bname = _esc(r.get("Baseline_Best", "--"))
        ename = _esc(r.get("ExtraEnsemble_Best", "--"))
        oname = _esc(r.get("Overall_Best", "--"))
        bauc = "--" if pd.isna(r.get("Baseline_AUC")) else f"{float(r['Baseline_AUC']):.3f}"
        eaux = "--" if pd.isna(r.get("ExtraEnsemble_AUC")) else f"{float(r['ExtraEnsemble_AUC']):.3f}"
        oauc = "--" if pd.isna(r.get("Overall_AUC")) else f"{float(r['Overall_AUC']):.3f}"
        lines.append(f"    {h} & {bname} & {bauc} & {ename} & {eaux} & {oname} & {oauc} " + nl)
    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("\\end{table}")
    out_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    df = build_dataframe()
    out = TABLES_DIR / "phase05_modeling_comparison.tex"
    if df.empty:
        out.write_text("% No evaluation results available yet", encoding="utf-8")
        print(f"Placeholder written: {out}")
        return
    write_tex(df, out)
    print(f"Generated: {out}")


if __name__ == "__main__":
    main()
