#!/usr/bin/env python3
"""
Generate LaTeX table(s) from Phase 06 model evaluation outputs.
- Reads results/06_model_evaluation/05_ALL_model_eval.xlsx (sheet 'All')
- Builds a compact ROC-AUC matrix: rows=models, columns=H1..H5
- Writes seminar-paper/tables/phase06_model_eval_matrix.tex
"""
from __future__ import annotations

from pathlib import Path
from typing import List
import pandas as pd
import json

ROOT = Path(__file__).resolve().parents[2]
EVAL_RESULTS = ROOT / "results" / "06_model_evaluation"
MOD_RESULTS = ROOT / "results" / "05_modeling"
MOD_RESULTS_EXTRA = MOD_RESULTS / "extra"
TABLES_DIR = ROOT / "seminar-paper" / "tables"
TABLES_DIR.mkdir(parents=True, exist_ok=True)


def _load_all_df() -> pd.DataFrame:
    xlsx = EVAL_RESULTS / "05_ALL_model_eval.xlsx"
    if xlsx.exists():
        try:
            return pd.read_excel(xlsx, sheet_name="All")
        except Exception:
            pass
    # Fallback: build from JSONs directly
    rows = []
    def ingest_dir(d: Path):
        for p in sorted(d.glob("H*_metrics.json")):
            try:
                blob = json.loads(p.read_text())
            except Exception:
                continue
            h = blob.get("horizon")
            for mname, s in (blob.get("metrics", {}) or {}).items():
                rows.append({
                    "Horizon": f"H{h}",
                    "Model": str(mname),
                    "ROC_AUC_Mean": s.get("roc_auc_mean"),
                    "PR_AUC_Mean": s.get("pr_auc_mean"),
                })
    ingest_dir(MOD_RESULTS)
    if MOD_RESULTS_EXTRA.exists():
        ingest_dir(MOD_RESULTS_EXTRA)
    return pd.DataFrame(rows)


def _esc_latex(text: str) -> str:
    s = str(text) if text is not None else ""
    repl = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    for k, v in repl.items():
        s = s.replace(k, v)
    return s


def write_auc_matrix(df: pd.DataFrame, out_path: Path) -> None:
    if df.empty:
        out_path.write_text("% No evaluation results available", encoding="utf-8")
        print(f"Placeholder written: {out_path}")
        return
    piv = df.pivot_table(index="Model", columns="Horizon", values="ROC_AUC_Mean", aggfunc="max")
    # Ensure H1..H5 ordering if present
    horizons: List[str] = [c for c in ["H1", "H2", "H3", "H4", "H5"] if c in piv.columns]
    piv = piv[horizons]
    # Sort models alphabetically for stability
    piv = piv.sort_index()

    lines: List[str] = []
    lines.append("% Auto-generated by generate_phase06_tables.py")
    lines.append(r"\begin{table}[H]")
    lines.append(r"  \centering")
    lines.append(r"  \caption{Modellvergleich (ROC-AUC) – alle Modelle je Horizont (Phase 05, Base + Extra)}")
    lines.append(r"  \label{tab:phase06_model_eval_matrix}")
    cols_spec = "l " + " ".join(["r" for _ in horizons])
    lines.append(fr"  \begin{{tabular}}{{{cols_spec}}}")
    lines.append(r"    \toprule")
    header = "Model" + " & " + " & ".join(horizons) + r" \\"
    lines.append("    " + header)
    lines.append(r"    \midrule")
    for model, row in piv.iterrows():
        vals = [f"{float(row[h]):.3f}" if pd.notnull(row[h]) else "--" for h in horizons]
        line = f"    {_esc_latex(model)} & " + " & ".join(vals) + r" \\"
        lines.append(line)
    lines.append(r"    \bottomrule")
    lines.append(r"  \end{tabular}")
    lines.append(r"\end{table}")
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated: {out_path}")


def main() -> None:
    df = _load_all_df()
    write_auc_matrix(df, TABLES_DIR / "phase06_model_eval_matrix.tex")


if __name__ == "__main__":
    main()
