#!/usr/bin/env python3
"""Generate LaTeX summary table for Phase 05 modeling (best ROC-/PR-AUC je Horizont)."""

from __future__ import annotations

import json
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
MOD_RESULTS = ROOT / "results" / "05_modeling"
MOD_RESULTS_EXTRA = MOD_RESULTS / "extra"
TABLES_DIR = ROOT / "seminar-paper" / "tables"
TABLES_DIR.mkdir(parents=True, exist_ok=True)


def _read_features_used_from_summary() -> dict[str, int]:
    mapping: dict[str, int] = {}
    xlsx = MOD_RESULTS / "ALL_summary.xlsx"
    if xlsx.exists():
        try:
            df = pd.read_excel(xlsx, sheet_name="Summary")
            if not df.empty:
                for _, r in df.iterrows():
                    h = str(r.get("Horizon"))
                    if pd.notnull(h) and pd.notnull(r.get("Features_Used")):
                        mapping[h] = int(r["Features_Used"])  # type: ignore[arg-type]
        except Exception:
            pass
    return mapping


def _collect_auc_by_horizon() -> dict[str, dict[str, float]]:
    by_h: dict[str, dict[str, float]] = {}

    def ingest_dir(d: Path):
        for p in sorted(d.glob("H*_metrics.json")):
            try:
                blob = json.loads(p.read_text())
            except Exception:
                continue
            h_raw = blob.get("horizon")
            if h_raw is None:
                continue
            h = f"H{int(h_raw)}"
            metrics: dict = blob.get("metrics", {})
            if not metrics:
                continue
            by_h.setdefault(h, {})
            for m_name, m_vals in metrics.items():
                auc = m_vals.get("roc_auc_mean")
                if auc is not None:
                    by_h[h][str(m_name)] = float(auc)

    ingest_dir(MOD_RESULTS)
    if MOD_RESULTS_EXTRA.exists():
        ingest_dir(MOD_RESULTS_EXTRA)
    return by_h


def load_best_rows() -> pd.DataFrame:
    features_map = _read_features_used_from_summary()
    auc_by_h = _collect_auc_by_horizon()
    rows: list[dict] = []
    for horizon, model_map in sorted(auc_by_h.items(), key=lambda kv: kv[0]):
        if not model_map:
            continue
        best_model, best_auc = max(model_map.items(), key=lambda kv: kv[1])
        pr_auc = None
        base_json = MOD_RESULTS / f"{horizon}_metrics.json"
        if base_json.exists():
            try:
                blob = json.loads(base_json.read_text())
                pr_auc = blob.get("metrics", {}).get(best_model, {}).get("pr_auc_mean")
            except Exception:
                pass
        if pr_auc is None and MOD_RESULTS_EXTRA.exists():
            extra_json = MOD_RESULTS_EXTRA / f"{horizon}_metrics.json"
            if extra_json.exists():
                try:
                    blob = json.loads(extra_json.read_text())
                    pr_auc = blob.get("metrics", {}).get(best_model, {}).get("pr_auc_mean")
                except Exception:
                    pass
        feats = features_map.get(horizon)
        rows.append({
            "Horizon": horizon,
            "Best_Model": best_model,
            "Best_ROC_AUC": best_auc,
            "Best_PR_AUC": pr_auc,
            "Features_Used": feats if feats is not None else None,
        })
    return pd.DataFrame(rows)


def write_tex(df: pd.DataFrame, out_path: Path):
    def esc(text: str) -> str:
        if text is None:
            return ""
        repl = {
            "\\": r"\textbackslash{}",
            "&": r"\&",
            "%": r"\%",
            "$": r"\$",
            "#": r"\#",
            "_": r"\_",
            "{": r"\{",
            "}": r"\}",
            "~": r"\textasciitilde{}",
            "^": r"\textasciicircum{}",
        }
        for k, v in repl.items():
            text = text.replace(k, v)
        return text
        header = r"""% Auto-generated by generate_phase05_tables.py
\begin{table}[H]
    \centering
    \caption{Modellgüte pro Horizont (beste ROC-AUC und PR-AUC)}
    \label{tab:phase05_modeling_summary}
    \begin{tabular}{l l r r r}
        	oprule
        Horizont & Bestes Modell & ROC-AUC & PR-AUC & Anzahl Features \\\\
        \midrule
"""
    lines: list[str] = []
    lines.append("% Auto-generated by generate_phase05_tables.py")
    lines.append(r"\begin{table}[H]")
    lines.append(r"  \centering")
    lines.append(r"  \caption{Modellgüte pro Horizont (beste ROC-AUC und PR-AUC)}")
    lines.append(r"  \label{tab:phase05_modeling_summary}")
    lines.append(r"  \begin{tabular}{l l r r r}")
    lines.append(r"    \toprule")
    lines.append(r"    Horizont & Bestes Modell & ROC-AUC & PR-AUC & Anzahl Features \\")
    lines.append(r"    \midrule")
    for _, r in df.sort_values("Horizon").iterrows():
        h = str(r["Horizon"]) if pd.notnull(r.get("Horizon")) else "--"
        model = esc(str(r.get("Best_Model", "--")))
        auc_val = r.get("Best_ROC_AUC")
        auc = f"{float(auc_val):.3f}" if pd.notnull(auc_val) else "--"
        pr_val = r.get("Best_PR_AUC")
        pr = f"{float(pr_val):.3f}" if (pr_val is not None and pd.notnull(pr_val)) else "--"
        feats = int(r["Features_Used"]) if pd.notnull(r.get("Features_Used")) else "--"
        # LaTeX row terminator needs double backslash
        lines.append("    " + h + " & " + model + " & " + auc + " & " + pr + " & " + str(feats) + " " + "\u005c\u005c")
    lines.append(r"    \bottomrule")
    lines.append(r"  \end{tabular}")
    lines.append(r"\end{table}")
    out_path.write_text("\n".join(lines), encoding="utf-8")


def main():
    df = load_best_rows()
    out = TABLES_DIR / "phase05_modeling_summary.tex"
    if df.empty:
        out.write_text("% No modeling results available yet", encoding="utf-8")
        print(f"Placeholder written: {out}")
        return
    write_tex(df, out)
    print(f"Generated: {out}")


if __name__ == "__main__":
    main()
